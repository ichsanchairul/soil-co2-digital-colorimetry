def load_image(image_path):
    image = Image.open(image_path)
    image = image.convert('RGB')
    return image

def extract_rgb(image):
    rgb_data = np.array(image) / 255.0
    return rgb_data

def convert_rgb_space(rgb_data, target_space_name):
    target_space = colour.RGB_COLOURSPACES[target_space_name]
    converted_rgb_data = colour.RGB_to_RGB(rgb_data, colour.RGB_COLOURSPACES['sRGB'], target_space)
