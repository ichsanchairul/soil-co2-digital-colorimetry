"""# CAM16UCS values extraction from digital images"""

import numpy as np
import matplotlib.pyplot as plt
from skimage import io, color
import cv2

def xyz_to_cam16ucs(xyz):
    """
    Approximate conversion from XYZ → CAM16-UCS using a linearized model.
    Output: array[..., 3] with J′, a′, b′
    """
    M = np.array([
        [0.7982,  0.3389, -0.1371],
        [-0.5918, 1.5512,  0.0406],
        [0.0008,  0.0239,  0.9753]
    ])

    xyz_transformed = np.dot(xyz, M.T)

    Jp = 100 * np.cbrt(np.clip(xyz_transformed[..., 1], 1e-6, None))
    ap = 175 * (xyz_transformed[..., 0] / np.clip(xyz_transformed[..., 1], 1e-6, None) - 0.3831)
    bp = 70  * (xyz_transformed[..., 2] / np.clip(xyz_transformed[..., 1], 1e-6, None) - 0.2489)

    return np.stack([Jp, ap, bp], axis=-1)

def extract_quantitative_cam16ucs(image_filename):
    image = io.imread(image_filename)

    if image.ndim == 2:
        image = color.gray2rgb(image)
    elif image.shape[2] == 4:
        image = image[..., :3]

    image = image / 255.0 if image.max() > 1.0 else image

    xyz_image = color.rgb2xyz(image)

    cam16ucs = xyz_to_cam16ucs(xyz_image)

    cam16ucs_norm = cam16ucs / np.max(cam16ucs)

    avg_values = np.mean(cam16ucs_norm, axis=(0, 1))

    print("✅ [Kuantitatif] Average normalized CAM16-UCS values:", avg_values)
    return cam16ucs_norm, avg_values

def visualize_cam16ucs(cam16ucs):
    """
    Menampilkan 3 channel (J′, a′, b′) dengan normalisasi per channel agar mudah dilihat.
    """
    channels = ['J′ (Lightness)', 'a′ (Red-Green)', 'b′ (Yellow-Blue)']
    plt.figure(figsize=(15, 4))

    for i in range(3):
        channel_img = cam16ucs[..., i]
        ch_norm = (channel_img - channel_img.min()) / (channel_img.max() - channel_img.min() + 1e-8)
        plt.subplot(1, 3, i + 1)
        plt.imshow(ch_norm, cmap='viridis')
        plt.title(channels[i])
        plt.axis('off')

    plt.suptitle("CAM16-UCS Channels Visualization", fontsize=14)
    plt.show()

image_path = "file-name.jpeg"

cam16ucs_norm, avg_values = extract_quantitative_cam16ucs(image_path)
visualize_cam16ucs(cam16ucs_norm)

