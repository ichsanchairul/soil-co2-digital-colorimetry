"""# CIELAB values extraction from digital images"""

from PIL import Image
from skimage import color
import numpy as np

def convert_to_cielab_with_normalization(image_path):
    """
    Convert an image to CIELAB color space and normalize values.

    Parameters:
    - image_path: Path to the input RGB image.

    Returns:
    - Normalized LAB image and average normalized LAB values.
    """
    image = Image.open(image_path).convert('RGB')

    image_array = np.array(image)

    lab_image = color.rgb2lab(image_array)

    lab_image[..., 0] = lab_image[..., 0] / 100.0

    lab_image[..., 1] = (lab_image[..., 1] + 128) / 255.0
    lab_image[..., 2] = (lab_image[..., 2] + 128) / 255.0

    average_normalized_lab = np.mean(lab_image, axis=(0, 1))

    return lab_image, average_normalized_lab

