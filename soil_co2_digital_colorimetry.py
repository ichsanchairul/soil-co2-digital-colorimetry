"""# CAM20u values extraction from digital images"""

from PIL import Image
import numpy as np
import matplotlib.pyplot as plt

Y_b = float(input("Enter background luminance (Y_b, in percentage, default=20): ") or 20)  # e.g., 20 for 20%
L_A = float(input("Enter adaptation luminance (L_A, in cd/m², default=64): ") or 64)  # e.g., 64 for indoor lighting

XYZ_D65 = [95.047, 100.0, 108.883]

def rgb_to_xyz(rgb):
    """
    Convert RGB to XYZ color space using the standard D65 illuminant.
    """
    rgb = np.asarray(rgb) / 255.0
    rgb = np.where(rgb <= 0.04045, rgb / 12.92, ((rgb + 0.055) / 1.055) ** 2.4)
    rgb = rgb.reshape(-1, 3)

    rgb_to_xyz_matrix = np.array([
        [0.4124564, 0.3575761, 0.1804375],
        [0.2126729, 0.7151522, 0.0721750],
        [0.0193339, 0.1191920, 0.9503041]
    ])
    xyz = np.dot(rgb, rgb_to_xyz_matrix.T)
    return xyz

def xyz_to_cam20u(xyz):
    """
    Convert XYZ to CAM20u color appearance model.
    """
    xyz_normalized = xyz / XYZ_D65

    X, Y, Z = xyz_normalized.T

    J = 100 * (Y / Y_b) ** (1 / 3)
    u = 13 * J * (X - 0.19783000664283)
    v = 13 * J * (Y - 0.46831999493879)

    return np.stack([J, u, v], axis=-1)

def process_image(image_file):
    """
    Load an image file, convert it to CAM20u color appearance model.
    """
    img = Image.open(image_file).convert("RGB")
    img_array = np.asarray(img)

    img_xyz = rgb_to_xyz(img_array)

    img_cam20u = xyz_to_cam20u(img_xyz)

    return img_cam20u, img_array.shape

image_file = "file-name.jpeg"

